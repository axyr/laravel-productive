<?php

declare(strict_types=1);

namespace Axyr\Productive\Generator\Emit;

use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Attribute;
use Axyr\Productive\Generator\Ir\Model;
use Axyr\Productive\Generator\Ir\Operation;
use Axyr\Productive\Generator\Ir\Relationship;
use Axyr\Productive\Generator\RecordedTypes;

/**
 * docs/spec-report.md: where Productive's OpenAPI spec and its API disagree, written for
 * Productive. Every entry names the endpoint and how to reproduce it; nothing names the test
 * organization, its people or its records.
 */
final readonly class SpecReportEmitter
{
    public const string PATH = 'docs/spec-report.md';

    /**
     * @param  list<string>  $enabled  The generated resource paths.
     * @param  array<string, list<string>>  $required  Required attributes `composer seed` found, by input class (generator/config/required.php).
     * @param  array<string, string>  $removed  Reasons by resource path or "type.relationship" (generator/config/removed.php).
     * @param  array<string, array<string, mixed>>  $recipes  The write recipes (generator/config/recipes.php).
     * @param  array{written: string, findings: array<string, list<array{endpoint: string, spec: string, api: string, reproduce: string}>>}  $findings  generator/config/spec-findings.php.
     */
    public function __construct(
        private Api $api,
        private array $enabled,
        private RecordedTypes $recorded,
        private array $required,
        private array $removed,
        private array $recipes,
        private array $findings,
    ) {}

    public function emit(): string
    {
        $writes = new SpecReportWrites($this->api, $this->recorded, $this->required, $this->recipes);
        $lines = [
            '# OpenAPI spec report',
            '',
            '<!-- Generated by `composer generate` from generator/recorded-types.json and generator/config. Do not edit by hand. -->',
            '',
            'Where the Productive API v2 and its OpenAPI spec disagree, found while generating a PHP SDK from the spec. Reads were recorded on ' . $this->recorded->recordedOn() . ', and writes on ' . $this->findings['written'] . ', against a trial organization. Every entry says how to reproduce it; `{id}` stands for the ID of any record of the organization.',
            ...Markdown::section('Required attributes the spec does not mark', 'The request answers 422 "can\'t be blank" without them. "Undocumented" means the spec does not list the attribute at all.', ['Endpoint', 'Attributes', 'Reproduce'], $writes->requiredRows()),
            ...Markdown::section('Bodies the spec does not document', 'The spec documents these operations without a request body. They accept these attributes.', ['Endpoint', 'Attributes', 'Reproduce'], $writes->bodyRows()),
            ...Markdown::section('Types that differ from the spec', 'Every recorded value had the recorded type, never the spec\'s.', ['Endpoint', 'Attribute', 'Spec', 'Recorded'], $this->typeRows()),
            ...Markdown::section('Undocumented attributes', 'Recorded responses carry them; the spec does not list them.', ['Endpoint', 'Attributes'], $this->modelRows(fn(Model $model): array => self::undocumentedAttributes($model))),
            ...Markdown::section('Undocumented relationships', 'Recorded responses carry them with data; the spec does not list them.', ['Endpoint', 'Relationships'], $this->modelRows(fn(Model $model): array => self::undocumentedRelationships($model))),
            ...Markdown::section('Example-only attributes', 'The spec\'s example has them, its schema does not, and no recorded response carried them.', ['Endpoint', 'Attributes'], $this->modelRows(fn(Model $model): array => $model->unseen)),
            ...Markdown::section('Includes the API rejects', 'The spec documents these relationships; including them answers 400 "Unsupported include".', ['Endpoint', 'Relationships', 'Reproduce'], $this->rejectedRows()),
            ...Markdown::section('Removed from the API', 'The spec still documents them.', ['Resource or relationship', 'What the API does'], self::pairs($this->removed)),
            ...Markdown::section('Resources outside the spec', 'The official Ruby client knows them and the API answers 200; the spec does not document them.', ['Endpoint'], $this->outsideRows()),
            ...$this->findingSections(),
        ];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @return list<list<string>>
     */
    private function typeRows(): array
    {
        $rows = [];

        foreach ($this->models() as $path => $model) {
            foreach ($model->attributes as $attribute) {
                if ($attribute->specType !== null) {
                    $rows[] = ['`GET /' . $path . '`', '`' . $attribute->name . '`', $attribute->specType->value, $attribute->type->value];
                }
            }
        }

        return $rows;
    }

    /**
     * One row per model with names, read where the model is listed.
     *
     * @param  callable(Model): list<string>  $names
     * @return list<list<string>>
     */
    private function modelRows(callable $names): array
    {
        $rows = [];

        foreach ($this->models() as $path => $model) {
            $found = $names($model);
            $rows[] = $found === [] ? null : ['`GET /' . $path . '`', Markdown::codes($found)];
        }

        return array_values(array_filter($rows));
    }

    /**
     * @return list<string>
     */
    private static function undocumentedAttributes(Model $model): array
    {
        return array_values(array_map(fn(Attribute $attribute): string => $attribute->name, array_filter($model->attributes, fn(Attribute $attribute): bool => $attribute->undocumented)));
    }

    /**
     * @return list<string>
     */
    private static function undocumentedRelationships(Model $model): array
    {
        return array_values(array_map(fn(Relationship $relationship): string => $relationship->name, array_filter($model->relationships, fn(Relationship $relationship): bool => $relationship->undocumented)));
    }

    /**
     * @return list<list<string>>
     */
    private function rejectedRows(): array
    {
        $rows = [];

        foreach ($this->recorded->rejectedIncludes() as $key => $names) {
            $operation = $this->operation($key);

            if ($operation !== null) {
                $rows[] = [self::endpoint($operation), Markdown::codes($names), sprintf('`GET /%s?include=%s`: 400.', $operation->path, $names[0])];
            }
        }

        return $rows;
    }

    /**
     * @return list<list<string>>
     */
    private function outsideRows(): array
    {
        $rows = [];

        foreach ($this->recorded->statuses() as $name => $status) {
            if (str_starts_with($name, 'undocumented.') && $status === 200) {
                $rows[] = ['`GET /' . str_replace('.', '/', substr($name, strlen('undocumented.'))) . '`'];
            }
        }

        return $rows;
    }

    /**
     * @return list<string>
     */
    private function findingSections(): array
    {
        $lines = [];

        foreach ($this->findings['findings'] as $title => $findings) {
            $rows = array_map(fn(array $finding): array => [$finding['endpoint'], $finding['spec'], $finding['api'], $finding['reproduce']], $findings);
            $lines = [...$lines, ...Markdown::section($title, 'Found by hand while recording and generating: the recordings alone do not show them.', ['Endpoint', 'Spec', 'API', 'Reproduce'], $rows)];
        }

        return $lines;
    }

    /**
     * @param  array<string, string>  $reasons
     * @return list<list<string>>
     */
    private static function pairs(array $reasons): array
    {
        return array_map(fn(string $name, string $reason): array => ['`' . $name . '`', $reason], array_keys($reasons), $reasons);
    }

    /**
     * The generated models by the path of the first resource listing them.
     *
     * @return array<string, Model>
     */
    private function models(): array
    {
        $models = [];

        foreach ($this->enabled as $path) {
            $model = $this->api->model((string) $this->api->resource($path)?->model);
            $known = array_map(fn(Model $seen): string => $seen->class, $models);

            if ($model !== null && ! in_array($model->class, $known, true)) {
                $models[$path] = $model;
            }
        }

        return $models;
    }

    private function operation(string $key): ?Operation
    {
        return SpecReportWrites::operation($this->api, $key);
    }

    private static function endpoint(Operation $operation): string
    {
        return SpecReportWrites::endpoint($operation);
    }
}
