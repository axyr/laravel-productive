<?php

declare(strict_types=1);

namespace Axyr\Productive\Generator\Emit;

use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Operation;
use Axyr\Productive\Generator\Ir\OperationKind;
use Axyr\Productive\Generator\Ir\Resource;
use Axyr\Productive\Generator\RecordedTypes;

/**
 * docs/coverage.md: one row per operation with how far it has been checked against the live API.
 * The page is done when no row is open: every operation is recorded, exercised, or carries the
 * reason it cannot be.
 */
final class CoverageEmitter
{
    public const string PATH = 'docs/coverage.md';

    /**
     * @param  list<string>  $enabled  The generated resource paths.
     * @param  array{skipped?: array<string, string>, plan_gated?: array<string, string>}  $reasons  By resource path or operation key.
     */
    public static function emit(Api $api, array $enabled, RecordedTypes $recorded, array $reasons): string
    {
        $resources = array_filter(array_map($api->resource(...), $enabled));
        $rows = [];

        foreach ($resources as $resource) {
            foreach ($resource->operations as $operation) {
                $rows[$resource->path][] = [$operation, ...self::status($resource, $operation, $recorded, $reasons)];
            }
        }

        return implode("\n", [...self::header($recorded, $rows), ...self::sections($rows)]) . "\n";
    }

    /**
     * @param  array<string, list<array{Operation, Coverage, string}>>  $rows
     * @return list<string>
     */
    private static function header(RecordedTypes $recorded, array $rows): array
    {
        $counts = self::counts($rows);
        $open = array_sum(array_map(fn(Coverage $coverage): int => $counts[$coverage->value] ?? 0, array_filter(Coverage::cases(), fn(Coverage $coverage): bool => $coverage->isOpen())));

        return [
            '# API coverage',
            '',
            '<!-- Generated by `composer generate` from generator/recorded-types.json. Do not edit by hand. -->',
            '',
            'Which operations the SDK has seen the live API answer. `composer record` records every GET of a test organization; writes are exercised by a live run that records their responses the same way. One row per operation of every generated resource' . ($recorded->recordedOn() === '' ? '.' : ', from the recording of ' . $recorded->recordedOn() . '.'),
            '',
            sprintf('**%d of %d operations are open:** recorded, exercised, or with the reason they cannot be is the goal; "empty list", "not recorded" and "not exercised" are the work left.', $open, array_sum($counts)),
            '',
            '| Status | Operations | Meaning |',
            '| --- | --- | --- |',
            ...array_map(fn(Coverage $coverage): string => sprintf('| %s | %d | %s |', $coverage->value, $counts[$coverage->value] ?? 0, $coverage->description()), Coverage::cases()),
        ];
    }

    /**
     * @param  array<string, list<array{Operation, Coverage, string}>>  $rows
     * @return array<string, int>  Operations per status.
     */
    private static function counts(array $rows): array
    {
        $counts = [];

        foreach ($rows as $operations) {
            foreach ($operations as [, $coverage]) {
                $counts[$coverage->value] = ($counts[$coverage->value] ?? 0) + 1;
            }
        }

        return $counts;
    }

    /**
     * @param  array<string, list<array{Operation, Coverage, string}>>  $rows
     * @return list<string>
     */
    private static function sections(array $rows): array
    {
        $lines = [];

        foreach ($rows as $path => $operations) {
            $lines = [...$lines, '', '## `' . $path . '`', '', '| Endpoint | Operation | Status |', '| --- | --- | --- |', ...array_map(self::row(...), $operations)];
        }

        return $lines;
    }

    /**
     * @param  array{Operation, Coverage, string}  $row
     */
    private static function row(array $row): string
    {
        [$operation, $coverage, $detail] = $row;

        return sprintf('| `%s /%s`%s | `%s` | %s%s |', $operation->httpMethod, $operation->path, $operation->bulk ? ' (bulk)' : '', $operation->key, $coverage->value, $detail === '' ? '' : ' ' . $detail);
    }

    /**
     * A success is evidence whatever the config says; then the configured reason; then the error
     * the API answered; then what nothing has called yet.
     *
     * @param  array{skipped?: array<string, string>, plan_gated?: array<string, string>}  $reasons
     * @return array{Coverage, string}
     */
    private static function status(Resource $resource, Operation $operation, RecordedTypes $recorded, array $reasons): array
    {
        $status = $recorded->statuses()[$operation->key] ?? null;

        if (self::isSuccess($status)) {
            return [$operation->httpMethod === 'GET' ? Coverage::Recorded : Coverage::Exercised, '`' . $status . '`'];
        }

        return self::reason($resource, $operation, $reasons) ?? self::failure($resource, $operation, $recorded, $status);
    }

    /**
     * @param  array{skipped?: array<string, string>, plan_gated?: array<string, string>}  $reasons
     * @return array{Coverage, string}|null
     */
    private static function reason(Resource $resource, Operation $operation, array $reasons): ?array
    {
        foreach (['skipped' => Coverage::Skipped, 'plan_gated' => Coverage::PlanGated] as $section => $coverage) {
            $reason = $reasons[$section][$operation->key] ?? $reasons[$section][$resource->path] ?? null;

            if ($reason !== null) {
                return [$coverage, $reason];
            }
        }

        return null;
    }

    /**
     * @return array{Coverage, string}
     */
    private static function failure(Resource $resource, Operation $operation, RecordedTypes $recorded, ?int $status): array
    {
        if ($status !== null) {
            return [Coverage::Rejected, '`' . $status . '`'];
        }

        if ($operation->httpMethod !== 'GET') {
            return [Coverage::NotExercised, ''];
        }

        return [self::listWasEmpty($resource, $operation, $recorded) ? Coverage::EmptyList : Coverage::NotRecorded, ''];
    }

    /**
     * Whether a show or GET action could not be recorded because the index had no record.
     */
    private static function listWasEmpty(Resource $resource, Operation $operation, RecordedTypes $recorded): bool
    {
        return $operation->kind !== OperationKind::Index && self::isSuccess(self::indexStatus($resource, $recorded));
    }

    private static function indexStatus(Resource $resource, RecordedTypes $recorded): ?int
    {
        foreach ($resource->operations as $candidate) {
            if ($candidate->kind === OperationKind::Index && $candidate->httpMethod === 'GET') {
                return $recorded->statuses()[$candidate->key] ?? null;
            }
        }

        return null;
    }

    private static function isSuccess(?int $status): bool
    {
        return $status !== null && $status >= 200 && $status < 300;
    }
}
