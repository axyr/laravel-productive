<?php

declare(strict_types=1);

namespace Axyr\Productive\Generator\Emit;

use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Operation;
use Axyr\Productive\Generator\Ir\Resource;

/**
 * docs/reference.md: every HTTP endpoint with the SDK method that calls it and the operation key
 * the testing fake matches on.
 */
final class ReferenceEmitter
{
    public const string PATH = 'docs/reference.md';

    /**
     * @param  list<string>  $enabled  The generated resource paths.
     */
    public static function emit(Api $api, array $enabled): string
    {
        $resources = array_filter(array_map($api->resource(...), $enabled));
        $operations = array_sum(array_map(fn(Resource $resource): int => count($resource->operations), $resources));

        $lines = [
            '# Endpoint reference',
            '',
            '<!-- Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand. -->',
            '',
            sprintf('Every endpoint of the Productive API with the SDK method that calls it: %d operations on %d resources. The operation key is what `Productive::fake()` seeds and asserts on.', $operations, count($resources)),
        ];

        foreach ($resources as $resource) {
            $lines = [...$lines, ...self::section($resource)];
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * @return list<string>
     */
    private static function section(Resource $resource): array
    {
        $accessor = 'Productive::' . ClientEmitter::accessor($resource) . '()';

        return [
            '',
            '## `' . $resource->path . '`',
            '',
            '| Endpoint | Method | Operation |',
            '| --- | --- | --- |',
            ...array_map(fn(Operation $operation): string => sprintf(
                '| `%s /%s`%s | `%s->%s()` | `%s` |',
                $operation->httpMethod,
                $operation->path,
                $operation->bulk ? ' (bulk)' : '',
                $accessor,
                $operation->method,
                $operation->key,
            ), $resource->operations),
        ];
    }
}
