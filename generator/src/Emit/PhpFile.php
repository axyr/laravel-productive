<?php

declare(strict_types=1);

namespace Axyr\Productive\Generator\Emit;

/**
 * Assembles a PHP source file: header, namespace, sorted imports and body.
 */
final class PhpFile
{
    public const MARKER = '// Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.';

    /**
     * @param  list<string>  $imports  Fully qualified class names, global ones included; duplicates and same-namespace classes are dropped.
     * @param  list<string>  $body
     */
    public static function render(string $namespace, array $imports, array $body): string
    {
        $uses = array_unique(array_filter($imports, fn(string $import): bool => self::needsImport($namespace, $import)));
        sort($uses);

        $lines = ['<?php', '', 'declare(strict_types=1);', '', self::MARKER, '', 'namespace ' . $namespace . ';', ''];

        if ($uses !== []) {
            array_push($lines, ...array_map(fn(string $use): string => 'use ' . $use . ';', $uses));
            $lines[] = '';
        }

        return implode("\n", [...$lines, ...$body]) . "\n";
    }

    /**
     * A docblock at the given indentation; empty strings become empty lines inside the block.
     *
     * @param  list<string>  $lines
     * @return list<string>
     */
    public static function docblock(array $lines, string $indent = ''): array
    {
        if ($lines === []) {
            return [];
        }

        $inner = array_map(fn(string $line): string => rtrim($indent . ' * ' . $line), $lines);

        return [$indent . '/**', ...$inner, $indent . ' */'];
    }

    private static function needsImport(string $namespace, string $import): bool
    {
        $position = strrpos($import, '\\');

        return $position === false || substr($import, 0, $position) !== $namespace;
    }
}
