<?php

declare(strict_types=1);

namespace Axyr\Productive\Generator\Emit;

use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Model;
use Axyr\Productive\Generator\Ir\Relationship;
use Axyr\Productive\Generator\Ir\Resource;
use Axyr\Productive\Generator\RecordedTypes;

/**
 * docs/api-differences.md: every place where recorded responses and the spec disagree, and what
 * the generator did about it.
 */
final class DifferencesEmitter
{
    public const string PATH = 'docs/api-differences.md';

    /**
     * @param  list<string>  $enabled  The generated resource paths.
     * @param  array{resources?: array<string, string>, relationships?: array<string, string>}  $removed  Reasons by path and by "type.relationship".
     */
    public static function emit(Api $api, array $enabled, RecordedTypes $recorded, array $removed): string
    {
        $models = self::models($api, $enabled);

        $lines = [
            '# API differences',
            '',
            '<!-- Generated by `composer generate` from generator/recorded-types.json. Do not edit by hand. -->',
            '',
            "Productive's OpenAPI spec does not always match what the API returns. `composer record` records real responses (GET only, from a trial organization), `composer record:types` reduces them to the kinds of value each attribute had, and `composer generate` follows the recording where the spec's type cannot read what the API sends. This page lists every difference" . ($recorded->recordedOn() === '' ? '.' : ' found in the recording of ' . $recorded->recordedOn() . '.'),
            ...self::section('Removed', 'The API no longer has these, so no code is generated for them.', ['Resource or relationship', 'Why'], self::removedRows($removed)),
            ...self::section('Types that differ from the spec', 'The generated property follows the recorded type. Null and empty values never override the spec.', ['Model', 'Attribute', 'Spec', 'Recorded'], self::overrideRows($models)),
            ...self::section('Undocumented attributes', 'Seen in recorded responses but missing from the spec. They are generated with their recorded type.', ['Model', 'Attribute', 'Type'], self::undocumentedAttributeRows($models)),
            ...self::section('Undocumented relationships', 'Seen with data in recorded responses but missing from the spec.', ['Model', 'Relationship', 'Kind', 'Target'], self::undocumentedRelationshipRows($models)),
            ...self::section('Example-only attributes never seen', 'The spec\'s example has them, its schema does not, and no recorded response of the type carried them. Their properties are kept, and have always been null, until Productive confirms whether they exist.', ['Model', 'Attribute'], self::unseenRows($models)),
            ...self::section('Relationships seen without data', 'Missing from the spec and recorded only as `{"meta": {"included": false}}`, so their cardinality is unknown and no accessor is generated yet. `composer record` includes them next time.', ['Type', 'Relationships'], self::untypedRows($recorded, $api)),
            ...self::section('Includes the API rejects', 'The spec documents these relationships, but the API answers 400 "Unsupported include".', ['Operation', 'Relationships'], self::rejectedRows($recorded)),
            ...self::section('Not checked', 'The recording token was not allowed to read these, so their spec types are kept.', ['Call', 'Status'], self::statusRows($recorded, fn(string $name, int $status): bool => in_array($status, [401, 403], true) && ! str_starts_with($name, 'undocumented.'))),
            ...self::section('Resources outside the spec', 'The official Ruby client knows these, the spec does not. 200 means the resource exists; it is not generated yet.', ['Resource', 'Status'], self::statusRows($recorded, fn(string $name): bool => str_starts_with($name, 'undocumented.'))),
            ...self::section('Not recorded yet', 'Their lists were empty in the recording, so they keep the spec\'s types.', ['Resource'], self::unrecordedRows($api, $enabled, $recorded)),
        ];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param  list<string>  $enabled
     * @return array<Model>
     */
    private static function models(Api $api, array $enabled): array
    {
        $classes = array_map(fn(string $path): ?string => $api->resource($path)?->model, $enabled);

        return array_filter($api->models, fn(Model $model): bool => in_array($model->class, $classes, true));
    }

    /**
     * @param  list<string>  $headers
     * @param  array<list<string>>  $rows
     * @return list<string>
     */
    private static function section(string $title, string $description, array $headers, array $rows): array
    {
        if ($rows === []) {
            return [];
        }

        $lines = ['', '## ' . $title, '', $description, '', '| ' . implode(' | ', $headers) . ' |', '|' . str_repeat(' --- |', count($headers))];

        foreach ($rows as $row) {
            $lines[] = '| ' . implode(' | ', $row) . ' |';
        }

        return $lines;
    }

    /**
     * @param  array{resources?: array<string, string>, relationships?: array<string, string>}  $removed
     * @return list<list<string>>
     */
    private static function removedRows(array $removed): array
    {
        $rows = [];

        foreach ([...$removed['resources'] ?? [], ...$removed['relationships'] ?? []] as $name => $reason) {
            $rows[] = ['`' . $name . '`', $reason];
        }

        return $rows;
    }

    /**
     * @param  array<Model>  $models
     * @return list<list<string>>
     */
    private static function overrideRows(array $models): array
    {
        $rows = [];

        foreach ($models as $model) {
            foreach ($model->attributes as $attribute) {
                if ($attribute->specType !== null) {
                    $rows[] = ['`' . $model->class . '`', '`' . $attribute->name . '`', $attribute->specType->value, $attribute->type->value];
                }
            }
        }

        return $rows;
    }

    /**
     * @param  array<Model>  $models
     * @return list<list<string>>
     */
    private static function undocumentedAttributeRows(array $models): array
    {
        $rows = [];

        foreach ($models as $model) {
            foreach ($model->attributes as $attribute) {
                if ($attribute->undocumented) {
                    $rows[] = ['`' . $model->class . '`', '`' . $attribute->name . '`', $attribute->type->value];
                }
            }
        }

        return $rows;
    }

    /**
     * @param  array<Model>  $models
     * @return list<list<string>>
     */
    private static function undocumentedRelationshipRows(array $models): array
    {
        $rows = [];

        foreach ($models as $model) {
            foreach (array_filter($model->relationships, fn(Relationship $relationship): bool => $relationship->undocumented) as $relationship) {
                $rows[] = ['`' . $model->class . '`', '`' . $relationship->name . '`', ...self::relationshipKind($relationship)];
            }
        }

        return $rows;
    }

    /**
     * @param  array<Model>  $models
     * @return list<list<string>>
     */
    private static function unseenRows(array $models): array
    {
        $rows = [];

        foreach ($models as $model) {
            foreach ($model->unseen as $name) {
                $rows[] = ['`' . $model->class . '`', '`' . $name . '`'];
            }
        }

        return $rows;
    }

    /**
     * @return array{string, string}  Cardinality and target.
     */
    private static function relationshipKind(Relationship $relationship): array
    {
        return [$relationship->toMany ? 'to-many' : 'to-one', $relationship->targetType === null ? 'any' : '`' . $relationship->targetType . '`'];
    }

    /**
     * @return array<list<string>>
     */
    private static function untypedRows(RecordedTypes $recorded, Api $api): array
    {
        $rows = [];

        foreach ($recorded->untypedRelationships() as $type => $names) {
            $missing = array_diff($names, self::relationshipNames($api, $type));
            $rows[] = $missing === [] ? null : ['`' . $type . '`', implode(', ', array_map(fn(string $name): string => '`' . $name . '`', $missing))];
        }

        return array_filter($rows);
    }

    /**
     * @return list<string>  The relationships the model of a type already has (the IR has one model per type).
     */
    private static function relationshipNames(Api $api, string $type): array
    {
        $models = array_filter($api->models, fn(Model $model): bool => $model->type === $type);
        $model = reset($models);

        return $model === false ? [] : array_map(fn(Relationship $relationship): string => $relationship->name, $model->relationships);
    }

    /**
     * @return list<list<string>>
     */
    private static function rejectedRows(RecordedTypes $recorded): array
    {
        $rows = [];

        foreach ($recorded->rejectedIncludes() as $operation => $names) {
            $rows[] = ['`' . $operation . '`', implode(', ', array_map(fn(string $name): string => '`' . $name . '`', $names))];
        }

        return $rows;
    }

    /**
     * @param  callable(string, int): bool  $filter
     * @return list<list<string>>
     */
    private static function statusRows(RecordedTypes $recorded, callable $filter): array
    {
        $rows = [];

        foreach ($recorded->statuses() as $name => $status) {
            if ($filter($name, $status)) {
                $rows[] = ['`' . preg_replace('/^undocumented\./', '', $name) . '`', sprintf('%d', $status)];
            }
        }

        return $rows;
    }

    /**
     * @param  list<string>  $enabled
     * @return array<list<string>>
     */
    private static function unrecordedRows(Api $api, array $enabled, RecordedTypes $recorded): array
    {
        $unrecorded = array_filter($enabled, fn(string $path): bool => self::isUnrecorded($api->resource($path), $recorded));

        return $recorded->statuses() === [] ? [] : array_map(fn(string $path): array => ['`' . $path . '`'], $unrecorded);
    }

    private static function isUnrecorded(?Resource $resource, RecordedTypes $recorded): bool
    {
        return $resource?->model !== null && ! $recorded->hasType($resource->type);
    }
}
