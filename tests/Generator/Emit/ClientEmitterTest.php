it('maps every model type, plus aliases of generated models only', function () {
    $models = [new Model('Task', 'tasks', '', [], []), new Model('Person', 'people', '', [], [])];

    expect(ClientEmitter::modelMap($models, ['users' => 'Person', 'ghosts' => 'Ghost']))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Data;

        use Axyr\Productive\Data\Models\Person;
        use Axyr\Productive\Data\Models\Task;

        /**
         * Built-in JSON:API type to model class map.
         */
        final class ModelMap
        {
            /** @var array<string, class-string<Model>> */
            public const MODELS = [
                Task::TYPE => Task::class,
                Person::TYPE => Person::class,
                'users' => Person::class,
            ];
        }
        PHP . "\n");
});

it('names the accessor chain of a resource', function () {
    expect(array_map(ClientEmitter::accessor(...), clientResources()))->toBe(['timeEntries', 'reports()->timeReports', 'tasks', 'public()->pages', 'reports()->budgetReports']);
});
