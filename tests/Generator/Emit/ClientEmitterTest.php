<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\ClientEmitter;
use Axyr\Productive\Generator\Ir\Model;
use Axyr\Productive\Generator\Ir\Resource;

/*
 * The exact client trait, group classes, facade and model map the emitter writes, checked by hand.
 */

function clientResource(string $path, string $class, string $namespace): Resource
{
    return new Resource($path, $class, $namespace, basename($path), null, []);
}

/**
 * @return list<Resource>
 */
function clientResources(): array
{
    return [
        clientResource('time_entries', 'TimeEntryResource', 'Axyr\\Productive\\Resources'),
        clientResource('reports/time_reports', 'TimeReportResource', 'Axyr\\Productive\\Resources\\Reports'),
        clientResource('tasks', 'TaskResource', 'Axyr\\Productive\\Resources'),
        clientResource('public/pages', 'PublicPageResource', 'Axyr\\Productive\\Resources\\Public'),
        clientResource('reports/budget_reports', 'BudgetReportResource', 'Axyr\\Productive\\Resources\\Reports'),
    ];
}

it('writes sorted accessors, the report and public groups and the facade', function () {
    expect(ClientEmitter::emit(clientResources()))->toBe([
        'src/Concerns/ProvidesResources.php' => <<<'PHP'
            <?php

            declare(strict_types=1);

            // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

            namespace Axyr\Productive\Concerns;

            use Axyr\Productive\Resources\Public\PublicResources;
            use Axyr\Productive\Resources\Reports\Reports;
            use Axyr\Productive\Resources\TaskResource;
            use Axyr\Productive\Resources\TimeEntryResource;

            /**
             * Accessors for every generated resource. Used by ProductiveClient.
             */
            trait ProvidesResources
            {
                public function public(): PublicResources
                {
                    return new PublicResources($this->connector(), $this->registry);
                }

                public function reports(): Reports
                {
                    return new Reports($this->connector(), $this->registry);
                }

                public function tasks(): TaskResource
                {
                    return new TaskResource($this->connector(), $this->registry);
                }

                public function timeEntries(): TimeEntryResource
                {
                    return new TimeEntryResource($this->connector(), $this->registry);
                }
            }
            PHP . "\n",
        'src/Resources/Reports/Reports.php' => <<<'PHP'
            <?php

            declare(strict_types=1);

            // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

            namespace Axyr\Productive\Resources\Reports;

            use Axyr\Productive\Contracts\ConnectorInterface;
            use Axyr\Productive\Data\ModelRegistry;

            /**
             * Entry point for the /reports endpoints: Productive::reports()->timeReports().
             */
            final readonly class Reports
            {
                public function __construct(
                    private ConnectorInterface $connector,
                    private ModelRegistry $registry,
                ) {}

                public function budgetReports(): BudgetReportResource
                {
                    return new BudgetReportResource($this->connector, $this->registry);
                }

                public function timeReports(): TimeReportResource
                {
                    return new TimeReportResource($this->connector, $this->registry);
                }
            }
            PHP . "\n",
        'src/Resources/Public/PublicResources.php' => <<<'PHP'
            <?php

            declare(strict_types=1);

            // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

            namespace Axyr\Productive\Resources\Public;

            use Axyr\Productive\Contracts\ConnectorInterface;
            use Axyr\Productive\Data\ModelRegistry;

            /**
             * Entry point for the public endpoints, which need no organization: Productive::public()->pages().
             */
            final readonly class PublicResources
            {
                public function __construct(
                    private ConnectorInterface $connector,
                    private ModelRegistry $registry,
                ) {}

                public function pages(): PublicPageResource
                {
                    return new PublicPageResource($this->connector, $this->registry);
                }
            }
            PHP . "\n",
        'src/ProductiveFacade.php' => <<<'PHP'
            <?php

            declare(strict_types=1);

            // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

            namespace Axyr\Productive;

            use Axyr\Productive\Testing\Concerns\FakesProductive;
            use Illuminate\Support\Facades\Facade;

            /**
             * @method static \Axyr\Productive\ProductiveClient withOrganization(string $organizationId)
             * @method static \Axyr\Productive\ProductiveClient withToken(string $token)
             * @method static \Axyr\Productive\Config\ProductiveConfig config()
             * @method static \Axyr\Productive\Contracts\ConnectorInterface connector()
             * @method static \Axyr\Productive\Resources\Public\PublicResources public()
             * @method static \Axyr\Productive\Resources\Reports\Reports reports()
             * @method static \Axyr\Productive\Resources\TaskResource tasks()
             * @method static \Axyr\Productive\Resources\TimeEntryResource timeEntries()
             *
             * @see ProductiveClient
             */
            class ProductiveFacade extends Facade
            {
                use FakesProductive;

                protected static function getFacadeAccessor(): string
                {
                    return ProductiveClient::class;
                }
            }
            PHP . "\n",
    ]);
});

