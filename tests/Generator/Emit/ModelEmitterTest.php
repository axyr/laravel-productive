<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\ModelEmitter;
use Axyr\Productive\Generator\Ir\Attribute;
use Axyr\Productive\Generator\Ir\AttributeType;
use Axyr\Productive\Generator\Ir\Model;
use Axyr\Productive\Generator\Ir\Relationship;

/*
 * The exact model class the emitter writes, checked by hand: typed properties with their docblocks,
 * one lenient reader per attribute, and accessors that resolve typed or generic relationships.
 */

it('writes typed properties, their readers and relationship accessors', function () {
    $model = new Model('Task', 'tasks', 'A unit of work.', [
        new Attribute('title', 'title', AttributeType::String, 'The task title.'),
        new Attribute('custom_fields', 'customFields', AttributeType::Object),
        new Attribute('tag_list', 'tagList', AttributeType::List, 'Tags on the task.'),
        new Attribute('type', 'typeValue', AttributeType::Int),
        new Attribute('due_date', 'dueDate', AttributeType::Date),
        new Attribute('data', 'data', AttributeType::Mixed),
    ], [
        new Relationship('project', false, 'projects'),
        new Relationship('parent_task', false, null),
        new Relationship('owner', false, 'unknowns'),
        new Relationship('assignees', true, 'people'),
        new Relationship('attachments', true, null),
    ]);

    expect((new ModelEmitter(['projects' => 'Project', 'people' => 'Person']))->emit($model, 'https://developer.productive.io/reference/tasks'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Data\Models;

        use Axyr\Productive\Data\Attributes;
        use Axyr\Productive\Data\Model;
        use DateTimeImmutable;

        /**
         * A unit of work.
         *
         * @see https://developer.productive.io/reference/tasks
         *
         * @SuppressWarnings("PHPMD.ExcessiveMethodLength")
         * @SuppressWarnings("PHPMD.ExcessiveClassComplexity")
         * @SuppressWarnings("PHPMD.TooManyFields")
         */
        final readonly class Task extends Model
        {
            public const string TYPE = 'tasks';

            /** The task title. */
            public ?string $title;

            /** @var array<array-key, mixed>|null */
            public ?array $customFields;

            /**
             * Tags on the task.
             *
             * @var list<mixed>|null
             */
            public ?array $tagList;

            public ?int $typeValue;

            public ?DateTimeImmutable $dueDate;

            public mixed $data;

            protected function hydrate(Attributes $attributes): void
            {
                $this->title = $attributes->string('title');
                $this->customFields = $attributes->object('custom_fields');
                $this->tagList = $attributes->list('tag_list');
                $this->typeValue = $attributes->int('type');
                $this->dueDate = $attributes->date('due_date');
                $this->data = $attributes->mixed('data');
            }

            public function project(): ?Project
            {
                return $this->belongsTo('project', Project::class);
            }

            public function parentTask(): ?Model
            {
                return $this->belongsTo('parent_task', Model::class);
            }

            public function owner(): ?Model
            {
                return $this->belongsTo('owner', Model::class);
            }

            /**
             * @return list<Person>
             */
            public function assignees(): array
            {
                return $this->hasMany('assignees', Person::class);
            }

            /**
             * @return list<Model>
             */
            public function attachments(): array
            {
                return $this->hasMany('attachments', Model::class);
            }
        }
        PHP . "\n");
});

it('leaves out the description, the date import and accessors when there are none', function () {
    $model = new Model('Tag', 'tags', '', [new Attribute('name', 'name', AttributeType::String)], []);

    expect((new ModelEmitter([]))->emit($model, 'https://developer.productive.io/reference/tags'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Data\Models;

        use Axyr\Productive\Data\Attributes;
        use Axyr\Productive\Data\Model;

        /**
         * @see https://developer.productive.io/reference/tags
         *
         * @SuppressWarnings("PHPMD.ExcessiveMethodLength")
         * @SuppressWarnings("PHPMD.ExcessiveClassComplexity")
         * @SuppressWarnings("PHPMD.TooManyFields")
         */
        final readonly class Tag extends Model
        {
            public const string TYPE = 'tags';

            public ?string $name;

            protected function hydrate(Attributes $attributes): void
            {
                $this->name = $attributes->string('name');
            }
        }
        PHP . "\n");
});
