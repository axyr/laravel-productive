/*
 * The exact contract test the emitter writes per kind of operation. Each expectation was checked by
 * hand against what the SDK sends and returns; the generated suite then runs these against the fake.
 */

function contractInput(): Input
{
    return new Input('CreateTaskData', 'task', [
        new Attribute('title', 'title', AttributeType::String, required: true),
        new Attribute('due_date', 'dueDate', AttributeType::Date),
    ]);
}

/**
 * @param  list<string>  $parameters
 */
function contractOperation(string $key, string $method, OperationKind $kind, string $httpMethod, string $path, array $parameters, ResponseKind $response, bool $bulk = false, ?string $operationId = null, ?Input $input = null, BodyKind $body = BodyKind::None): Operation
{
    return new Operation($key, $method, $kind, $httpMethod, $path, $parameters, $response, $bulk, true, $operationId, $input, body: $body);
}

/**
 * The emitted file from its first test on, for one operation of the tasks resource.
 */
function contractTestFor(Operation $operation, ?Resource $resource = null): string
{
    $file = ContractTestEmitter::emit($resource ?? new Resource('tasks', 'TaskResource', 'X', 'tasks', 'Task', [$operation]), $resource === null ? 'Task' : 'Proposal');

    return substr($file, (int) strpos($file, 'it('));
}

it('writes a complete test file with one test per operation', function () {
    $resource = new Resource('tasks', 'TaskResource', 'Axyr\\Productive\\Resources', 'tasks', 'Task', [
        contractOperation('tasks.index', 'query', OperationKind::Index, 'GET', 'tasks', [], ResponseKind::Collection, operationId: 'tasks-index'),
        contractOperation('tasks.create', 'create', OperationKind::Create, 'POST', 'tasks', [], ResponseKind::Resource, operationId: 'tasks-create', input: contractInput(), body: BodyKind::Attributes),
        contractOperation('tasks.update', 'update', OperationKind::Update, 'PATCH', 'tasks/{id}', ['id'], ResponseKind::Resource, operationId: 'tasks-update', input: contractInput(), body: BodyKind::Attributes),
    ]);

    expect(ContractTestEmitter::emit($resource, 'Task'))->toBe(<<<'PHP'
