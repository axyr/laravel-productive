<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\DifferencesEmitter;
use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Attribute;
use Axyr\Productive\Generator\Ir\AttributeType;
use Axyr\Productive\Generator\Ir\Model;
use Axyr\Productive\Generator\Ir\Relationship;
use Axyr\Productive\Generator\Ir\Resource;
use Axyr\Productive\Generator\RecordedTypes;

function differencesApi(): Api
{
    $task = new Model('Task', 'tasks', '', [
        new Attribute('title', 'title', AttributeType::String),
        new Attribute('draft', 'draft', AttributeType::Bool, specType: AttributeType::Int),
        new Attribute('level', 'level', AttributeType::Int, undocumented: true),
    ], [
        new Relationship('project', false, 'projects'),
        new Relationship('todos', true, 'todos', undocumented: true),
        new Relationship('owner', false, null, undocumented: true),
    ], unseen: ['url', 'events']);
    $hidden = new Model('Hidden', 'hidden', '', [new Attribute('x', 'x', AttributeType::Int, specType: AttributeType::String, undocumented: true)], [new Relationship('y', false, null, undocumented: true)]);

    return new Api([
        new Resource('tasks', 'TaskResource', 'X', 'tasks', 'Task', []),
        new Resource('teams', 'TeamResource', 'X', 'teams', 'Team', []),
        new Resource('reports/time_reports', 'TimeReportResource', 'X', 'time_reports', null, []),
        new Resource('hidden', 'HiddenResource', 'X', 'hidden', 'Hidden', []),
    ], [$hidden, $task]);
}

it('lists every difference between the recording and the spec', function () {
    $recorded = new RecordedTypes([
        'recorded_on' => '2026-10-09',
        'statuses' => [
            'agents.index' => 403,
            'login.index' => 401,
            'tasks.index' => 200,
            'undocumented.meetings' => 200,
            'undocumented.booking_items' => 404,
            'undocumented.secrets' => 403,
        ],
        'rejected_includes' => ['reports.task_reports.index' => ['board', 'organization']],
        'types' => [
            'tasks' => ['relationships' => ['subtasks' => ['to_many' => null], 'owner' => ['to_many' => null], 'project' => ['to_many' => false, 'types' => ['projects']]]],
            'people' => ['relationships' => ['manager' => ['to_many' => null], 'owner' => ['to_many' => null]]],
            'hidden' => ['relationships' => ['y' => ['to_many' => null]]],
        ],
    ]);
    $removed = ['resources' => ['boards' => 'Gone.'], 'relationships' => ['task_lists.board' => 'Folders now.']];

    expect(DifferencesEmitter::emit(differencesApi(), ['tasks', 'teams', 'reports/time_reports'], $recorded, $removed))->toBe(<<<'MD'
        # API differences

        <!-- Generated by `composer generate` from generator/recorded-types.json. Do not edit by hand. -->

        Productive's OpenAPI spec does not always match what the API returns. `composer record` records real responses (GET only, from a trial organization), `composer record:types` reduces them to the kinds of value each attribute had, and `composer generate` follows the recording where the spec's type cannot read what the API sends. This page lists every difference found in the recording of 2026-10-09.

        ## Removed

        The API no longer has these, so no code is generated for them.

        | Resource or relationship | Why |
        | --- | --- |
        | `boards` | Gone. |
        | `task_lists.board` | Folders now. |

        ## Types that differ from the spec

        The generated property follows the recorded type. Null and empty values never override the spec.

        | Model | Attribute | Spec | Recorded |
        | --- | --- | --- | --- |
        | `Task` | `draft` | int | bool |

        ## Undocumented attributes

        Seen in recorded responses but missing from the spec. They are generated with their recorded type.

        | Model | Attribute | Type |
        | --- | --- | --- |
        | `Task` | `level` | int |

        ## Undocumented relationships

        Seen with data in recorded responses but missing from the spec.

        | Model | Relationship | Kind | Target |
        | --- | --- | --- | --- |
        | `Task` | `todos` | to-many | `todos` |
        | `Task` | `owner` | to-one | any |

        ## Example-only attributes never seen

        The spec's example has them, its schema does not, and no recorded response of the type carried them. Their properties are kept, and have always been null, until Productive confirms whether they exist.

        | Model | Attribute |
        | --- | --- |
        | `Task` | `url` |
        | `Task` | `events` |

        ## Relationships seen without data

        Missing from the spec and recorded only as `{"meta": {"included": false}}`, so their cardinality is unknown and no accessor is generated yet. `composer record` includes them next time.

        | Type | Relationships |
        | --- | --- |
        | `tasks` | `subtasks` |
        | `people` | `manager`, `owner` |

        ## Includes the API rejects

        The spec documents these relationships, but the API answers 400 "Unsupported include".

        | Operation | Relationships |
        | --- | --- |
        | `reports.task_reports.index` | `board`, `organization` |

        ## Not checked

        The recording token was not allowed to read these, so their spec types are kept.

        | Call | Status |
        | --- | --- |
        | `agents.index` | 403 |
        | `login.index` | 401 |

        ## Resources outside the spec

        The official Ruby client knows these, the spec does not. 200 means the resource exists; it is not generated yet.

        | Resource | Status |
        | --- | --- |
        | `meetings` | 200 |
        | `booking_items` | 404 |
        | `secrets` | 403 |

        ## Not recorded yet

        Their lists were empty in the recording, so they keep the spec's types.

        | Resource |
        | --- |
        | `teams` |

        MD);
});

it('leaves out empty sections and the date when nothing was recorded', function () {
    $markdown = DifferencesEmitter::emit(differencesApi(), ['teams', 'not/in/the/spec'], new RecordedTypes(), []);

    expect($markdown)->toEndWith("This page lists every difference.\n")
        ->and($markdown)->not->toContain('##');
});

it('skips enabled paths the API description does not know', function () {
    $markdown = DifferencesEmitter::emit(differencesApi(), ['tasks', 'not/in/the/spec'], new RecordedTypes(['statuses' => ['tasks.index' => 200]]), []);

    expect($markdown)->toContain('| `Task` | `draft` | int | bool |')
        ->and($markdown)->not->toContain('not/in/the/spec');
});
