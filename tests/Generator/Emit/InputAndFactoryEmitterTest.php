<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\FactoryEmitter;
use Axyr\Productive\Generator\Emit\InputEmitter;
use Axyr\Productive\Generator\Ir\Attribute;
use Axyr\Productive\Generator\Ir\AttributeType;
use Axyr\Productive\Generator\Ir\Input;
use Axyr\Productive\Generator\Ir\Model;

/*
 * The exact input and factory classes the emitters write, checked by hand.
 */

it('writes an input with required fields first, Undefined defaults and formatted dates', function () {
    $input = new Input('CreateTaskData', 'task', [
        new Attribute('title', 'title', AttributeType::String, 'The title.', required: true),
        new Attribute('project_id', 'projectId', AttributeType::Int, required: true),
        new Attribute('due_date', 'dueDate', AttributeType::Date),
        new Attribute('due_time', 'dueTime', AttributeType::Time),
        new Attribute('started_at', 'startedAt', AttributeType::DateTime),
        new Attribute('tag_list', 'tagList', AttributeType::List, 'Tags.', items: AttributeType::String),
        new Attribute('custom_fields', 'customFields', AttributeType::Object),
        new Attribute('estimate', 'estimate', AttributeType::Float),
        new Attribute('private', 'private', AttributeType::Bool),
        new Attribute('cost', 'cost', AttributeType::Mixed),
    ]);

    expect(InputEmitter::emit($input, 'Create a task.'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Data\Input;

        use Axyr\Productive\Data\InputData;
        use Axyr\Productive\Data\Undefined;
        use DateTimeInterface;

        /**
         * Create a task.
         *
         * @SuppressWarnings("PHPMD.ExcessiveParameterList")
         * @SuppressWarnings("PHPMD.ExcessiveMethodLength")
         */
        final readonly class CreateTaskData extends InputData
        {
            /**
             * @param  list<string>|Undefined|null  $tagList  Tags.
             * @param  array<string, mixed>|Undefined|null  $customFields
             */
            public function __construct(
                public string $title,
                public int|string $projectId,
                public DateTimeInterface|string|Undefined|null $dueDate = Undefined::Value,
                public DateTimeInterface|string|Undefined|null $dueTime = Undefined::Value,
                public DateTimeInterface|string|Undefined|null $startedAt = Undefined::Value,
                public array|Undefined|null $tagList = Undefined::Value,
                public array|Undefined|null $customFields = Undefined::Value,
                public float|int|Undefined|null $estimate = Undefined::Value,
                public bool|Undefined|null $private = Undefined::Value,
                public mixed $cost = Undefined::Value,
            ) {}

            public function toAttributes(): array
            {
                return self::filter([
                    'title' => $this->title,
                    'project_id' => $this->projectId,
                    'due_date' => self::date($this->dueDate),
                    'due_time' => self::time($this->dueTime),
                    'started_at' => $this->startedAt,
                    'tag_list' => $this->tagList,
                    'custom_fields' => $this->customFields,
                    'estimate' => $this->estimate,
                    'private' => $this->private,
                    'cost' => $this->cost,
                ]);
            }
        }
        PHP . "\n");
});

it('imports neither Undefined nor DateTimeInterface for an input of required plain fields', function () {
    $input = new Input('MergeData', 'merge', [
        new Attribute('ids', 'ids', AttributeType::List, required: true),
        new Attribute('name', 'name', AttributeType::String, required: true),
    ]);

    expect(InputEmitter::emit($input, 'Merge records.'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Data\Input;

        use Axyr\Productive\Data\InputData;

        /**
         * Merge records.
         */
        final readonly class MergeData extends InputData
        {
            /**
             * @param  list<mixed>  $ids
             */
            public function __construct(
                public array $ids,
                public string $name,
            ) {}

            public function toAttributes(): array
            {
                return self::filter([
                    'ids' => $this->ids,
                    'name' => $this->name,
                ]);
            }
        }
        PHP . "\n");
});

it('writes a factory whose defaults are the example without id and type', function () {
    $model = new Model('Task', 'tasks', '', [], [], ['id' => '1', 'type' => 'tasks', 'title' => 'Plan', 'hours' => 1.5, 'tags' => ['a'], 'meta' => ['k' => null]]);

    expect(FactoryEmitter::emit($model))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Testing\Factories;

        use Axyr\Productive\Data\Models\Task;

        /**
         * Defaults are the attributes of the example in Productive's API reference.
         *
         * @extends Factory<Task>
         *
         * @SuppressWarnings("PHPMD.ExcessiveMethodLength")
         */
        final class TaskFactory extends Factory
        {
            public static function new(): self
            {
                return new self();
            }

            protected function model(): string
            {
                return Task::class;
            }

            protected function definition(): array
            {
                return [
                    'title' => 'Plan',
                    'hours' => 1.5,
                    'tags' => ['a'],
                    'meta' => ['k' => null],
                ];
            }
        }
        PHP . "\n");
});

