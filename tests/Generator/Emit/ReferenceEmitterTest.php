<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\ReferenceEmitter;
use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Operation;
use Axyr\Productive\Generator\Ir\OperationKind;
use Axyr\Productive\Generator\Ir\Resource;
use Axyr\Productive\Generator\Ir\ResponseKind;

it('lists every endpoint of the enabled resources with its method and operation key', function () {
    $operation = fn(string $key, string $method, string $http, string $path, bool $bulk = false): Operation => new Operation($key, $method, OperationKind::Action, $http, $path, [], ResponseKind::Resource, $bulk, true, $key);
    $api = new Api([
        new Resource('tasks', 'TaskResource', 'X', 'tasks', 'Task', [$operation('tasks.index', 'query', 'GET', 'tasks'), $operation('tasks.create_bulk', 'bulkCreate', 'POST', 'tasks', bulk: true)]),
        new Resource('reports/time_reports', 'TimeReportResource', 'X', 'time_reports', 'TimeReport', [$operation('reports.time_reports.index', 'query', 'GET', 'reports/time_reports')]),
        new Resource('boards', 'BoardResource', 'X', 'boards', 'Board', [$operation('boards.index', 'query', 'GET', 'boards')]),
    ], []);

    expect(ReferenceEmitter::emit($api, ['tasks', 'reports/time_reports', 'unknown']))->toBe(<<<'MD'
        # Endpoint reference

        <!-- Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand. -->

        Every endpoint of the Productive API with the SDK method that calls it: 3 operations on 2 resources. The operation key is what `Productive::fake()` seeds and asserts on.

        ## `tasks`

        | Endpoint | Method | Operation |
        | --- | --- | --- |
        | `GET /tasks` | `Productive::tasks()->query()` | `tasks.index` |
        | `POST /tasks` (bulk) | `Productive::tasks()->bulkCreate()` | `tasks.create_bulk` |

        ## `reports/time_reports`

        | Endpoint | Method | Operation |
        | --- | --- | --- |
        | `GET /reports/time_reports` | `Productive::reports()->timeReports()->query()` | `reports.time_reports.index` |

        MD);
});
