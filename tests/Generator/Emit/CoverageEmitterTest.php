});

it('shows a recorded success whatever the config says, and no date without a recording', function () {
    $recorded = new RecordedTypes(['statuses' => ['agents.index' => 200]]);
    $markdown = CoverageEmitter::emit(coverageApi(), ['agents'], $recorded, ['plan_gated' => ['agents' => 'Not in the plan.']]);

    expect($markdown)->toContain('every generated resource.')
        ->and($markdown)->toContain('| `GET /agents` | `agents.index` | recorded `200` |')
        ->and($markdown)->toContain('| `GET /agents/{id}` | `agents.show` | plan-gated Not in the plan. |')
        ->and($markdown)->toContain('**0 of 2 operations are open:**');
});
