<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\CoverageEmitter;
use Axyr\Productive\Generator\Ir\Api;
use Axyr\Productive\Generator\Ir\Operation;
use Axyr\Productive\Generator\Ir\OperationKind;
use Axyr\Productive\Generator\Ir\Resource;
use Axyr\Productive\Generator\Ir\ResponseKind;
use Axyr\Productive\Generator\RecordedTypes;

function coverageOperation(string $key, OperationKind $kind, string $http, string $path, bool $bulk = false): Operation
{
    return new Operation($key, 'x', $kind, $http, $path, [], ResponseKind::Resource, $bulk, true, $key);
}

function coverageApi(): Api
{
    return new Api([
        new Resource('agents', 'AgentResource', 'X', 'agents', 'Agent', [
            coverageOperation('agents.index', OperationKind::Index, 'GET', 'agents'),
            coverageOperation('agents.show', OperationKind::Show, 'GET', 'agents/{id}'),
        ]),
        new Resource('integrations', 'IntegrationResource', 'X', 'integrations', 'Integration', [
            coverageOperation('integrations.index', OperationKind::Index, 'GET', 'integrations'),
            coverageOperation('integrations.sync', OperationKind::Action, 'GET', 'integrations/{id}/sync'),
        ]),
        new Resource('invoices', 'InvoiceResource', 'X', 'invoices', 'Invoice', [
            coverageOperation('invoices.index', OperationKind::Index, 'GET', 'invoices'),
            coverageOperation('invoices.show', OperationKind::Show, 'GET', 'invoices/{id}'),
            coverageOperation('invoices.preview', OperationKind::Action, 'GET', 'invoices/{id}/preview'),
            coverageOperation('invoices.create', OperationKind::Create, 'POST', 'invoices'),
            coverageOperation('invoices.destroy', OperationKind::Destroy, 'DELETE', 'invoices/{id}'),
            coverageOperation('invoices.create_bulk', OperationKind::CreateBulk, 'POST', 'invoices', bulk: true),
        ]),
        new Resource('sessions', 'SessionResource', 'X', 'sessions', 'Session', [
            coverageOperation('sessions.index', OperationKind::Index, 'GET', 'sessions'),
        ]),
        new Resource('teams', 'TeamResource', 'X', 'teams', 'Team', [
            coverageOperation('teams.index', OperationKind::Index, 'GET', 'teams'),
            coverageOperation('teams.show', OperationKind::Show, 'GET', 'teams/{id}'),
            coverageOperation('teams.update', OperationKind::Update, 'PATCH', 'teams/{id}'),
        ]),
        new Resource('timers', 'TimerResource', 'X', 'timers', 'Timer', [
            coverageOperation('timers.show', OperationKind::Show, 'GET', 'timers/{id}'),
            coverageOperation('timers.stop', OperationKind::Action, 'PATCH', 'timers/{id}/stop'),
        ]),
    ], []);
}

it('gives every operation of the enabled resources a status', function () {
    $recorded = new RecordedTypes([
        'recorded_on' => '2026-10-23',
        'statuses' => [
            'agents.index' => 403,
            'integrations.index' => 200,
            'invoices.index' => 200,
            'invoices.show' => 200,
            'invoices.preview' => 400,
            'invoices.create' => 201,
            'invoices.destroy' => 204,
            'teams.index' => 200,
            'timers.stop' => 500,
        ],
    ]);
    $reasons = [
        'skipped' => ['sessions' => 'Authentication.', 'integrations.sync' => 'Starts a sync.', 'invoices.preview' => 'Would be shown as recorded if it had succeeded.'],
        'plan_gated' => ['agents' => 'Not in the plan.', 'teams.update' => 'Teams cannot be renamed on this plan.'],
    ];

    expect(CoverageEmitter::emit(coverageApi(), ['agents', 'integrations', 'invoices', 'sessions', 'teams', 'timers', 'not/in/the/spec'], $recorded, $reasons))->toBe(<<<'MD'
