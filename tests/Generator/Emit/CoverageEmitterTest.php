        | exercised | 2 | A write a live run answered with a success. |
        | empty list | 1 | The list was empty, so there was no record to fetch. Seed the organization and record again. |
        | rejected | 1 | The API answered with an error; the status is shown. |
        | plan-gated | 3 | The test organization's plan does not include it. |
        | skipped | 3 | Left out on purpose; the reason is shown. |
        | not recorded | 1 | A GET nothing has called yet. |
        | not exercised | 1 | A write nothing has called yet. |

        ## `agents`

        | Endpoint | Operation | Status |
        | --- | --- | --- |
        | `GET /agents` | `agents.index` | plan-gated Not in the plan. |
        | `GET /agents/{id}` | `agents.show` | plan-gated Not in the plan. |

        ## `integrations`

        | Endpoint | Operation | Status |
        | --- | --- | --- |
        | `GET /integrations` | `integrations.index` | recorded `200` |
        | `GET /integrations/{id}/sync` | `integrations.sync` | skipped Starts a sync. |

        ## `invoices`

        | Endpoint | Operation | Status |
        | --- | --- | --- |
        | `GET /invoices` | `invoices.index` | recorded `200` |
