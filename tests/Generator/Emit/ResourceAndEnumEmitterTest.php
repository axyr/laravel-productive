<?php

declare(strict_types=1);

use Axyr\Productive\Generator\Emit\EnumEmitter;
use Axyr\Productive\Generator\Emit\ResourceEmitter;
use Axyr\Productive\Generator\Ir\Operation;
use Axyr\Productive\Generator\Ir\OperationKind;
use Axyr\Productive\Generator\Ir\Resource;
use Axyr\Productive\Generator\Ir\ResponseKind;

/*
 * The exact resource classes and enums the emitters write, checked by hand.
 */

it('writes a resource with its constants and one method per operation', function () {
    $resource = new Resource('tasks', 'TaskResource', 'Axyr\\Productive\\Resources', 'tasks', 'Task', [
        new Operation('tasks.index', 'query', OperationKind::Index, 'GET', 'tasks', [], ResponseKind::Collection, false, true, 'tasks-index'),
        new Operation('tasks.destroy', 'delete', OperationKind::Destroy, 'DELETE', 'tasks/{id}', ['id'], ResponseKind::NoContent, false, true, 'tasks-destroy'),
    ]);

    expect(ResourceEmitter::emit($resource, 'Task', 'A unit of work.', 'https://developer.productive.io/reference/tasks'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Resources;

        use Axyr\Productive\Data\Models\Task;
        use Axyr\Productive\Http\Method;

        /**
         * A unit of work.
         *
         * @see https://developer.productive.io/reference/tasks
         */
        final class TaskResource extends Resource
        {
            protected const string TYPE = 'tasks';

            protected const string PATH = 'tasks';

            /**
             * GET /tasks
             *
             * @return PendingQuery<Task>
             */
            public function query(): PendingQuery
            {
                return $this->newQuery(Task::class, 'tasks.index');
            }

            /**
             * DELETE /tasks/{id}
             */
            public function delete(int|string $id): void
            {
                $this->writeWithoutResponse(Method::Delete, $this->path($id), 'tasks.destroy');
            }
        }
        PHP . "\n");
});

it('pages a report by number and throttles it as a report', function () {
    $resource = new Resource('reports/time_reports', 'TimeReportResource', 'Axyr\\Productive\\Resources\\Reports', 'time_reports', 'TimeReport', [
        new Operation('reports.time_reports.index', 'query', OperationKind::Index, 'GET', 'reports/time_reports', [], ResponseKind::Collection, false, true, 'x'),
    ], supportsCursor: false, reportRateLimit: true);

    expect(ResourceEmitter::emit($resource, 'TimeReport', '', 'https://developer.productive.io/reference/time_reports'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Resources\Reports;

        use Axyr\Productive\Data\Models\TimeReport;
        use Axyr\Productive\Http\RateLimit;
        use Axyr\Productive\Resources\PendingQuery;
        use Axyr\Productive\Resources\Resource;

        /**
         * @see https://developer.productive.io/reference/time_reports
         */
        final class TimeReportResource extends Resource
        {
            protected const string TYPE = 'time_reports';

            protected const string PATH = 'reports/time_reports';

            protected const bool SUPPORTS_CURSOR = false;

            /**
             * GET /reports/time_reports
             *
             * @return PendingQuery<TimeReport>
             */
            public function query(): PendingQuery
            {
                return $this->newQuery(TimeReport::class, 'reports.time_reports.index');
            }

            protected function rateLimits(): array
            {
                return [RateLimit::reports()];
            }
        }
        PHP . "\n");
});

it('marks a resource public when any of its operations needs no organization', function () {
    $resource = new Resource('public/pages', 'PublicPageResource', 'Axyr\\Productive\\Resources\\Public', 'pages', 'Page', [
        new Operation('public.pages.index', 'query', OperationKind::Index, 'GET', 'public/pages', [], ResponseKind::Collection, false, true, 'x'),
        new Operation('public.pages.show', 'find', OperationKind::Show, 'GET', 'public/pages/{uuid}', ['uuid'], ResponseKind::Resource, false, false, 'x'),
    ]);

    expect(ResourceEmitter::emit($resource, 'Page', '', 'https://developer.productive.io/reference/pages'))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Resources\Public;

        use Axyr\Productive\Data\Models\Page;
        use Axyr\Productive\Query\Query;
        use Axyr\Productive\Resources\PendingQuery;
        use Axyr\Productive\Resources\Resource;

        /**
         * @see https://developer.productive.io/reference/pages
         */
        final class PublicPageResource extends Resource
        {
            protected const string TYPE = 'pages';

            protected const string PATH = 'public/pages';

            protected const bool REQUIRES_ORGANIZATION = false;

            /**
             * GET /public/pages
             *
             * @return PendingQuery<Page>
             */
            public function query(): PendingQuery
            {
                return $this->newQuery(Page::class, 'public.pages.index');
            }

            /**
             * GET /public/pages/{uuid}
             *
             * @param  list<string>  $include
             */
            public function find(string $uuid, array $include = []): Page
            {
                return $this->fetchOne(Page::class, $this->path($uuid), 'public.pages.show', (new Query())->include(...$include));
            }
        }
        PHP . "\n");
});

it('writes sort enums with a Desc case for descending values', function () {
    expect(EnumEmitter::sort('TaskSort', 'Sort options.', ['due_date', '-due_date', 'title']))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Enums;

        /**
         * Sort options.
         */
        enum TaskSort: string
        {
            case DueDate = 'due_date';
            case DueDateDesc = '-due_date';
            case Title = 'title';
        }
        PHP . "\n");
});

it('writes group enums', function () {
    expect(EnumEmitter::group('TimeReportGroup', 'Groups.', ['person', 'project_type']))->toBe(<<<'PHP'
        <?php

        declare(strict_types=1);

        // Generated by `composer generate` from resources/openapi/productive.json. Do not edit by hand.

        namespace Axyr\Productive\Enums;

        /**
         * Groups.
         */
        enum TimeReportGroup: string
        {
            case Person = 'person';
            case ProjectType = 'project_type';
        }
        PHP . "\n");
});

it('refuses two values that become the same case', function () {
    expect(fn() => EnumEmitter::group('X', 'd', ['due-date', 'due_date']))->toThrow(RuntimeException::class, 'X: "due-date" and "due_date" both become case DueDate.');
});
